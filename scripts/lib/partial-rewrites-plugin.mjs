// Vite plugin: rewrites applied to every mirrored partial as it is imported.
//
// Every mirrored partial is pulled in as an `?raw` HTML import, so this is the
// one boundary that catches pages, posts, archives and the shared chrome at
// once — rather than repeating the work in each route that renders them.
//
// All rewrites are build-time only; the partials on disk stay as generated.
import fs from 'node:fs/promises';
import { toMediaOrigin } from './config.mjs';
import { normalizeLinks } from './normalize-links.mjs';
import { applyHtmlPerf } from './html-perf.mjs';

/** One entry of the Resources mega-menu, matched by the page it links to. */
const resourcesItem = path =>
  new RegExp(`<li class="elementor-icon-list-item">\\s*<a href="${path}">[\\s\\S]*?</li>\\s*`, 'g');

/**
 * Business Roaming Plans, the last entry of the mega-menu's left column — once
 * in the desktop panel, once in the mobile drawer.
 */
const RESOURCES_ROAMING_ITEM = resourcesItem('/business-roaming-packs/');

/**
 * "API Documentation", which takes its place.
 *
 * The link is ours, not WordPress': it points at the docs site, which lives off
 * this domain, so it opens in a new tab. Injected here rather than written into
 * `partials/chrome/header.html` because that file is regenerated by the mirror
 * and would lose the edit on the next run. The markup copies its siblings so
 * the mega-menu's icon-list CSS styles it with nothing new.
 *
 * Substituted rather than appended so it lands in the left column's third row,
 * level with Support in the right one. Appending after Support instead left the
 * vacated row empty and hung the new entry below the panel's last line.
 */
const API_DOCS_ITEM = `<li class="elementor-icon-list-item">
											<a href="https://docs.spenza.com" target="_blank" rel="noopener noreferrer">

											<span class="elementor-icon-list-text">API Documentation</span>
											</a>
									</li>
								`;

/**
 * "US Mobile Plans", dropped from Resources.
 *
 * Removed rather than substituted, because Support sits directly after it in
 * both the desktop panel and the mobile drawer — so deleting the row lets
 * Support move up into it, which is the placement asked for. The page itself
 * stays reachable at its own URL.
 */
const RESOURCES_US_PLANS_ITEM = resourcesItem('/unlimited-data-plans-pricing/');

/** Resources loses Business Roaming Plans and gains the docs link in its slot. */
function editResourcesMenu(html) {
  return html
    .replace(RESOURCES_ROAMING_ITEM, () => API_DOCS_ITEM)
    .replace(RESOURCES_US_PLANS_ITEM, '');
}

/**
 * The mobile hamburger, as WordPress draws it: five segments forming three
 * broken rows of unequal length.
 */
const SEGMENTED_BURGER =
  'M6.66666 11.6667H11.6667M33.3333 11.6667H18.3333M33.3333 28.3333H28.3333M6.66666 28.3333H21.6667M6.66666 20H33.3333';

/**
 * Three equal rules, on the same three baselines and between the same margins,
 * so nothing about the icon's size, weight or alignment changes — only the
 * broken segments become whole.
 */
const PLAIN_BURGER = 'M6.66666 11.6667H33.3333M6.66666 20H33.3333M6.66666 28.3333H33.3333';

/**
 * Swaps in the plain hamburger.
 *
 * Rewritten here rather than in `partials/chrome/header.html` for the same
 * reason as the docs link above: that file is regenerated by the mirror and
 * would lose the edit on the next run. Doing it at build time also beats doing
 * it in the shim, which would paint the original icon first.
 */
function plainHamburgerIcon(html) {
  return html.replace(SEGMENTED_BURGER, PLAIN_BURGER);
}

export function partialRewrites() {
  return {
    name: 'spenza:partial-rewrites',
    enforce: 'pre',

    /**
     * Loads the partial itself rather than transforming Vite's output.
     *
     * By the time a `?raw` import reaches `transform` it is a JS module holding
     * one string literal, with every `"` escaped to `\"` — so patterns written
     * against real HTML silently never match. Reading the file here means the
     * rewrites run on actual markup.
     */
    async load(id) {
      if (!id.endsWith('.html?raw')) return null;
      if (!id.includes('/partials/') && !id.includes('\\partials\\')) return null;

      const file = id.slice(0, -'?raw'.length);
      const html = await fs.readFile(file, 'utf8');
      let out = normalizeLinks(html);
      if (/chrome[/\\]header\.html$/.test(file)) out = plainHamburgerIcon(editResourcesMenu(out));
      out = toMediaOrigin(applyHtmlPerf(out));
      return `export default ${JSON.stringify(out)}`;
    },
  };
}
