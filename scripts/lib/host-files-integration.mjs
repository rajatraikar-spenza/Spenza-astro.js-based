// Astro integration: the files a static host needs, written at build time.
//
// Three jobs, all of which have to happen after the pages exist:
//
//   _redirects  WordPress' 301s as real redirects, not the meta-refresh pages a
//               static build has to fall back to.
//   _headers    Cache and security policy. The CSS bundles are content-addressed
//               and Astro's assets are hashed, so both can be cached forever —
//               they were being served with no cache policy at all.
//   prune       Delete CSS nothing links to. `dist` carried 87MB of it.
//
// Generated into `dist` rather than committed to `public/`, because all three
// depend on data that changes (the redirect table, the environment, which
// bundles the optimiser produced) and a committed copy would go stale silently.
//
// The `_redirects` and `_headers` formats are shared by Cloudflare Pages and
// Netlify. Vercel wants the same rules expressed in `vercel.json`.
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NOINDEX, IS_DEFAULT_SITE, MEDIA_ORIGIN, WEBP_PATH, toMediaOrigin } from './config.mjs';
import wpRedirects from '../../src/data/wp-redirects.json' with { type: 'json' };

/**
 * Long enough to be worth setting, short enough to survive a mistake.
 *
 * `immutable` is only safe on a path whose name changes with its content —
 * anything else and a bad deploy is cached in readers' browsers for a year with
 * no way to reach them.
 */
const YEAR = 'public, max-age=31536000, immutable';
const MONTH = 'public, max-age=2592000';

/**
 * Ordered general-to-specific. Both hosts apply every matching block in file
 * order, with later blocks overriding earlier ones for the same header, so the
 * catch-all has to come first or it would flatten the caching rules below it.
 *
 * Deliberately absent from HSTS: `includeSubDomains` and `preload`. The zone has
 * siblings (api, telematics, docs, and a media host to come) and forcing HTTPS
 * on all of them from here — irreversibly, in the case of preload — is not this
 * file's call to make. Add them once every subdomain is known to be HTTPS.
 */
const HEADERS = `# Generated by scripts/lib/host-files-integration.mjs — do not edit.

/*
  Cache-Control: public, max-age=0, must-revalidate
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN
  Strict-Transport-Security: max-age=31536000

# Content-addressed: the filename changes whenever the bytes do.
/wp-assets/_opt/*
  Cache-Control: ${YEAR}

/_astro/*
  Cache-Control: ${YEAR}

# Mirrored theme and plugin assets — fonts, icons, images. Stable in practice,
# but the names are WordPress', not content hashes, so no immutable.
/wp-assets/*
  Cache-Control: ${MONTH}

/wp-content/uploads/*
  Cache-Control: ${MONTH}

# Images this repo serves under its own names. Stable, but not hashed.
/images/*
  Cache-Control: ${MONTH}

# Except this one: everything in it is named by a hash of its bytes, whether
# written by extractInlineImages below or checked into public/. Without this
# block the extraction pass moved 0.3MB out of the HTML and into files the
# browser then re-validated on every single page load — the bytes stopped
# blocking first paint, which was the point, but nothing was ever cached.
/images/inline/*
  Cache-Control: ${YEAR}

/scripts/*
  Cache-Control: ${MONTH}

# Pinned third-party libraries. The version is in the filename — they are
# referenced from JS rather than from markup, so the digest stamper below never
# sees them, and an upgrade has to arrive as a new name to reach anyone's cache.
/vendor/*
  Cache-Control: ${YEAR}
`;

const NOINDEX_HEADERS = `
# NOINDEX is set — keep this deployment out of search results even for URLs
# discovered by a link rather than a crawl of robots.txt.
/*
  X-Robots-Tag: noindex, nofollow
`;

/**
 * WordPress' 301s, as host rules.
 *
 * Sources are written exactly as the redirect table records them. Normalising
 * them to the site's trailing-slash convention first would turn the `/blog` ->
 * `/blog/` entry into a rule pointing at itself, which is a redirect loop
 * rather than a tidier rule.
 */
function buildRedirects() {
  const lines = [
    '# Generated by scripts/lib/host-files-integration.mjs — do not edit.',
    '# Source: src/data/wp-redirects.json (npm run wp:redirects)',
    '',
  ];
  let skipped = 0;
  for (const [from, to] of Object.entries(wpRedirects)) {
    if (from === to) { skipped++; continue; }
    lines.push(`${from}  ${to}  301`);
  }
  return { body: lines.join('\n') + '\n', count: lines.length - 3, skipped };
}

/** Every file under `dir`, as absolute paths. */
async function walk(dir, out = []) {
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) await walk(p, out);
    else out.push(p);
  }
  return out;
}

const IMPORT_RE = /@import\s+(?:url\(\s*(["']?)([^"')]+)\1\s*\)|(["'])((?:\\.|(?!\3).)*)\3)/g;

/**
 * Delete CSS no built page can reach.
 *
 * Driven by what the output actually references rather than by a list of paths
 * believed to be safe — the reachable set is computed from the `<link>` tags in
 * every built page, then closed over `@import` so a stylesheet pulled in by
 * another stylesheet is kept too. Anything outside that closure is unreachable
 * by construction, which is a much stronger guarantee than "these directories
 * looked unused".
 *
 * There is a lot of it: the optimiser emits a bundle for all 487 mirrored page
 * keys, but every post now renders headless through one shared set, so the
 * per-post bundles are built, shipped and never requested. They stay in the
 * repo — they are the rollback for a post put back on the mirror — and are
 * simply not deployed.
 */
async function pruneUnreferencedCss(out, logger) {
  const files = await walk(out);
  const html = files.filter(f => f.endsWith('.html'));
  const css = files.filter(f => f.endsWith('.css'));
  if (!css.length) return;

  const toAbs = href => path.join(out, decodeURIComponent(href.split(/[?#]/)[0]));

  const keep = new Set();
  const queue = [];
  const consider = href => {
    if (!href || !href.startsWith('/')) return;
    const abs = toAbs(href);
    if (keep.has(abs)) return;
    keep.add(abs);
    queue.push(abs);
  };

  for (const f of html) {
    const text = await fs.readFile(f, 'utf8');
    for (const tag of text.matchAll(/<link\b[^>]*>/g)) {
      if (!/rel=["']stylesheet["']/.test(tag[0])) continue;
      consider(/href=["']([^"']+)["']/.exec(tag[0])?.[1]);
    }
    // Inline <style> blocks reach stylesheets too. The mirrored post bodies
    // carry `@import` inside their own <style>, which is how the self-hosted
    // Google Fonts are pulled in — counting only <link> deleted those as
    // unreferenced and left two posts pointing at a file that was no longer
    // there. A stylesheet is reachable however the page reaches it.
    for (const block of text.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)) {
      for (const m of block[1].matchAll(IMPORT_RE)) consider(m[2] ?? m[4]);
    }
  }

  const fromHtml = keep.size;

  while (queue.length) {
    const abs = queue.pop();
    let text;
    try {
      text = await fs.readFile(abs, 'utf8');
    } catch {
      continue; // A referenced file that is not there is the audit's problem.
    }
    for (const m of text.matchAll(IMPORT_RE)) consider(m[2] ?? m[4]);
  }

  const dead = css.filter(f => !keep.has(f));
  if (!dead.length) return;

  let freed = 0;
  for (const f of dead) {
    freed += (await fs.stat(f)).size;
    await fs.rm(f);
  }

  logger.info(
    `pruned ${dead.length} unreferenced stylesheets, ${(freed / 1048576).toFixed(1)}MB ` +
    `(kept ${fromHtml} linked + ${keep.size - fromHtml} imported)`
  );
}

/**
 * Move base64 images out of the HTML and into files.
 *
 * Elementor exports some illustrations as inline `<svg>` with the raster inside
 * them as a `data:` URI. On the home page that is seven images and 417KB of the
 * 1.55MB document — one of them a 1254x1254 PNG on its own — and base64 is the
 * worst possible place for it: it cannot be cached, cannot be lazy-loaded,
 * cannot be fetched in parallel, and compresses badly because the bytes are
 * already compressed. It is pure blocking weight in front of first paint, which
 * is exactly what Lighthouse measured on mobile: a 542KB document and an LCP of
 * 7.1s on a page whose LCP element is a heading.
 *
 * Extracted to a content-addressed file so it caches forever, and referenced by
 * URL. The bytes are re-encoded only if the encoder produces a smaller file
 * that is still the same format — an `<image>` inside an SVG is not a
 * `<picture>` and has no fallback, so this is not the place to change formats.
 *
 * The threshold keeps small inline icons where they are: below a couple of KB
 * an extra request costs more than the bytes save.
 */
const INLINE_IMAGE_MIN = 2048;

async function extractInlineImages(out, logger) {
  const html = (await walk(out)).filter(f => f.endsWith('.html'));
  if (!html.length) return;

  const { createHash } = await import('node:crypto');
  let sharp;
  try {
    ({ default: sharp } = await import('sharp'));
  } catch {
    // Astro ships sharp for its image service; if that ever changes, extraction
    // still works, just without the recompression pass.
  }

  const dir = path.join(out, 'images', 'inline');
  /** data URI -> public path, so one image shared by ten pages is written once. */
  const seen = new Map();
  let files = 0, saved = 0, pages = 0;

  const DATA_URI = /data:image\/(png|jpeg|jpg|gif|webp|avif);base64,([A-Za-z0-9+/=]+)/g;

  for (const file of html) {
    const text = await fs.readFile(file, 'utf8');
    if (!text.includes(';base64,')) continue;

    let touched = false;
    const next = await replaceAsync(text, DATA_URI, async (uri, type, b64) => {
      if (uri.length < INLINE_IMAGE_MIN) return uri;

      let url = seen.get(uri);
      if (!url) {
        let buf = Buffer.from(b64, 'base64');
        const ext = type === 'jpg' ? 'jpeg' : type;
        // PNG only: re-encoding a JPEG loses detail every time it runs, and
        // this pass exists to move bytes, not to change what they show.
        if (sharp && ext === 'png') buf = await shrinkPng(buf, sharp);
        const name = `${createHash('sha256').update(buf).digest('hex').slice(0, 12)}.${ext === 'jpeg' ? 'jpg' : ext}`;
        await fs.mkdir(dir, { recursive: true });
        await fs.writeFile(path.join(dir, name), buf);
        url = `/images/inline/${name}`;
        seen.set(uri, url);
        files++;
        saved += uri.length - buf.length;
      }
      touched = true;
      return url;
    });

    if (!touched) continue;
    await fs.writeFile(file, next, 'utf8');
    pages++;
  }

  if (files) {
    logger.info(
      `extracted ${files} inline images to /images/inline, ` +
      `${(saved / 1048576).toFixed(1)}MB out of ${pages} documents`
    );
  }
}

/**
 * The smallest honest PNG: re-deflated, or palette-reduced when that provably
 * changes nothing anyone can see.
 *
 * The 1254x1254 robot on the home page is two flat colours over transparency
 * stored as 24-bit RGBA — 294KB where a palette holds it in 33KB, identically.
 * A photograph put through the same encoder bands visibly, so the palette
 * version is only accepted after being compared against the original: flat
 * artwork comes back with a mean channel error near zero, a photograph does
 * not. The threshold is well below the ~2/255 at which a difference starts to
 * be perceptible on a gradient.
 */
async function shrinkPng(buf, sharp) {
  const candidates = [buf];

  try {
    candidates.push(await sharp(buf)
      .png({ compressionLevel: 9, effort: 10, palette: false })
      .toBuffer());
  } catch { /* the original stays in the running */ }

  try {
    const paletted = await sharp(buf).png({ palette: true, quality: 80, effort: 10 }).toBuffer();
    if (await meanChannelError(buf, paletted, sharp) < 0.5) candidates.push(paletted);
  } catch { /* likewise */ }

  return candidates.reduce((a, b) => (b.length < a.length ? b : a));
}

/** Mean absolute per-channel difference between two encodings, 0-255. */
async function meanChannelError(a, b, sharp) {
  const to = img => sharp(img)
    .resize({ width: 400, height: 400, fit: 'fill' })
    .ensureAlpha()
    .raw()
    .toBuffer();
  const [ra, rb] = await Promise.all([to(a), to(b)]);
  if (ra.length !== rb.length) return Infinity;
  let sum = 0;
  for (let i = 0; i < ra.length; i++) sum += Math.abs(ra[i] - rb[i]);
  return sum / ra.length;
}

/** `String.replace` with an async replacer, which the platform still lacks. */
async function replaceAsync(text, re, fn) {
  const jobs = [];
  text.replace(re, (...args) => { jobs.push(fn(...args)); return ''; });
  const values = await Promise.all(jobs);
  let i = 0;
  return text.replace(re, () => values[i++]);
}

/**
 * Start a stylesheet's `@import` downloading with the stylesheet itself.
 *
 * The optimiser's bundle opens with `@import "…/font-awesome/all.min.css"`, and
 * an `@import` is the one way to load CSS that cannot be discovered in advance:
 * the browser has to fetch the bundle, parse it, and only then learn about the
 * second file — two serial round trips in front of the first paint, on the
 * connection that is already the critical path. Lighthouse costed that one
 * import at 949ms of render-blocking on mobile.
 *
 * A `preload` fixes the round trip and nothing else. Promoting the import to a
 * real `<link rel="stylesheet">` was the first attempt and it made articles
 * slower — a second sheet ahead of the bundle in a bandwidth-limited simulation
 * pushed FCP from 1.7s to 3.9s — because the browser fetches stylesheets in
 * document order and the bundle is the one the page is actually waiting on.
 * Preloading keeps the bundle first and the import merely warm: by the time the
 * parser reaches the `@import`, the response is already in the cache.
 *
 * Runs before the prune, which decides what is reachable by reading the markup,
 * so the imported file stays as reachable as it was.
 */
async function hoistCssImports(out, logger) {
  const all = await walk(out);
  const sheets = all.filter(f => f.endsWith('.css'));

  // Only leading imports: one that follows a rule would have been ignored by
  // CSS anyway, and a preload for it would warm a file the page never uses.
  const LEADING_IMPORT = /@import\s+(?:url\(\s*)?["'](\/[^"')]+)["']\s*\)?\s*;/g;

  /** public path of a stylesheet -> what it imports, in order. */
  const imported = new Map();

  for (const file of sheets) {
    const text = await fs.readFile(file, 'utf8');
    const head = text.slice(0, 2000);          // imports are at the top or nowhere
    const imports = [...head.matchAll(LEADING_IMPORT)].map(m => m[1]);
    if (!imports.length) continue;
    imported.set('/' + path.relative(out, file).split(path.sep).join('/'), imports);
  }

  if (!imported.size) return;

  let pages = 0, links = 0;
  for (const file of all.filter(f => f.endsWith('.html'))) {
    const before = await fs.readFile(file, 'utf8');
    let after = before;

    for (const [sheet, imports] of imported) {
      if (!after.includes(`href="${sheet}"`)) continue;
      const add = imports
        .filter(href => !after.includes(`rel="preload" as="style" href="${href}"`))
        .map(href => `<link rel="preload" as="style" href="${href}">`)
        .join('');
      if (!add) continue;
      // Ahead of the first stylesheet link, so the preload is issued with the
      // rest of the head rather than after them.
      const at = after.indexOf('<link rel="stylesheet"');
      if (at < 0) continue;
      after = after.slice(0, at) + add + after.slice(at);
      links += imports.length;
    }

    if (after === before) continue;
    await fs.writeFile(file, after, 'utf8');
    pages++;
  }

  logger.info(`preloaded ${links} @import targets across ${pages} pages`);
}

/**
 * Serve every font from this origin, and let text paint before it arrives.
 *
 * `wp:fonts` mirrors the stylesheets the *markup* asks for, but Elementor and
 * Astra carry their own `@font-face` blocks inside the theme CSS, and those name
 * fonts.gstatic.com directly. So two families were still fetched from Google on
 * every page — a third-party DNS lookup and TLS handshake in front of first
 * paint, on a site that otherwise contacts nobody. The woff2 they point at are
 * already mirrored under `_fonts/`, filed by Google's own basename, so this is
 * a rename rather than a download.
 *
 * `font-display` is the other half. Without it a face blocks text for up to
 * three seconds while it loads, which Lighthouse costed at 1,150ms on a post —
 * and it is the icon fonts, 371KB of Font Awesome and eicons, that take longest.
 * `swap` paints in the fallback immediately and swaps when the face lands.
 */
async function fixFontLoading(out, logger) {
  const css = (await walk(out)).filter(f => f.endsWith('.css'));
  const fontsDir = path.join(out, 'wp-assets', '_fonts');
  const mirrored = new Set(await fs.readdir(fontsDir).catch(() => []));

  const GSTATIC = /https:\/\/fonts\.gstatic\.com\/[^"')\s]+?\/([A-Za-z0-9_-]+\.woff2?)/g;
  const FACE = /@font-face\s*\{[^}]*\}/g;

  let repointed = 0, displayed = 0, touched = 0;

  for (const file of css) {
    const before = await fs.readFile(file, 'utf8');
    let after = before.replace(GSTATIC, (url, name) => {
      if (!mirrored.has(name)) return url;   // Not mirrored: leave it working.
      repointed++;
      return `/wp-assets/_fonts/${name}`;
    });

    after = after.replace(FACE, block => {
      if (/font-display\s*:/.test(block)) return block;
      displayed++;
      // The separator matters: the minifier drops the last semicolon in a
      // block, so appending without one glues the new property onto the end of
      // `unicode-range` and CSS then discards *both* — which would silently
      // undo the subsetting and pull down every language's woff2.
      return block.replace(/;?\s*\}$/, ';font-display:swap}');
    });

    if (after === before) continue;
    await fs.writeFile(file, after, 'utf8');
    touched++;
  }

  if (touched) {
    logger.info(
      `fonts: repointed ${repointed} URLs at this origin and added font-display ` +
      `to ${displayed} faces across ${touched} stylesheets`
    );
  }
}

/**
 * Point media URLs inside the built CSS and JS at the media host.
 *
 * Markup gets this at import time, where the rewrite can run on the partial
 * before it becomes a JS string. The other two carriers have no such hook:
 * `public/scripts/` is copied verbatim, and the CSS bundles are committed
 * artefacts that must stay environment-neutral so the same bytes can be built
 * for staging, production, or no media host at all. So both are rewritten here,
 * against the finished output, where the environment is finally known.
 *
 * Small in volume and large in consequence: one avatar URL across 257 script
 * bundles, and five `background-image` declarations. All six would have become
 * 404s the moment the media trees stopped being deployed.
 */
/**
 * Stamp the site's own scripts with a digest of what they contain.
 *
 * `/scripts/*` is served with a month's `max-age` and its names are ours, not
 * content hashes, so a reader who has been here before keeps running whatever
 * `wp-shim.js` they were given last time — for thirty days, through refreshes,
 * through new tabs, and through a CloudFront invalidation, because the stale
 * copy is on their machine and nothing asks the network about it. The themed
 * `<select>` shipped and no returning reader saw it; that is the shape of the
 * bug, and it applies equally to every fix that lands in this directory.
 *
 * The HTML is `max-age=0, must-revalidate`, so a changed `src` reaches everyone
 * on their next page load. Appending the digest makes the URL change exactly
 * when the bytes do: no bump to remember, and an unchanged script keeps its
 * name and stays cached. The query string is enough — browsers key their cache
 * on the full URL — and it holds whether or not the CDN forwards it, since the
 * origin serves the same file either way.
 *
 * Only `/scripts/` is covered. The vendored `/wp-assets/` JS is WordPress' and
 * does not change; if that ever stops being true, widen the pattern rather than
 * bumping something by hand.
 */
async function versionScripts(out, logger) {
  const pages = (await walk(out)).filter(f => f.endsWith('.html'));
  if (!pages.length) return;

  const digests = new Map();
  const digestFor = async url => {
    if (digests.has(url)) return digests.get(url);
    let hash = null;
    try {
      const buf = await fs.readFile(path.join(out, url.slice(1)));
      hash = createHash('sha256').update(buf).digest('hex').slice(0, 8);
    } catch {
      // Referenced but not built. Leaving the URL alone keeps the 404 honest
      // rather than dressing it up with a version it does not have.
    }
    digests.set(url, hash);
    return hash;
  };

  // Already-versioned URLs are excluded by the `[^"?#]` class, so the pass is
  // idempotent and a rebuild over a dirty `dist` cannot stack query strings.
  const re = /(<script\b[^>]*\ssrc=")(\/scripts\/[^"?#]+\.js)(")/g;
  let stamped = 0;
  let touched = 0;

  for (const file of pages) {
    const html = await fs.readFile(file, 'utf8');
    const next = await replaceAsync(html, re, async (whole, head, url, tail) => {
      const hash = await digestFor(url);
      if (!hash) return whole;
      stamped++;
      return `${head}${url}?v=${hash}${tail}`;
    });
    if (next !== html) {
      await fs.writeFile(file, next, 'utf8');
      touched++;
    }
  }

  logger.info(`scripts: versioned ${stamped} references across ${touched} pages`);
}

async function rewriteAssetMedia(out, logger) {
  if (!MEDIA_ORIGIN) return;
  const files = (await walk(out)).filter(f => f.endsWith('.js') || f.endsWith('.css'));
  let js = 0, css = 0;
  for (const f of files) {
    const before = await fs.readFile(f, 'utf8');
    const after = toMediaOrigin(before);
    if (after === before) continue;
    await fs.writeFile(f, after, 'utf8');
    if (f.endsWith('.css')) css++; else js++;
  }
  if (js || css) logger.info(`repointed media URLs in ${js} scripts and ${css} stylesheets`);
}

/**
 * The media trees, relative to the output root. These are what the bucket
 * serves, so shipping them as well would double the bytes and leave two copies
 * to keep in step.
 *
 * The third is the asset mirror's duplicate of five uploads, filed under
 * `/wp-assets/` by a rule meant for plugin assets. `toMediaUrl` rewrites those
 * references to the canonical `/wp-content/uploads/` spelling, so the copies are
 * unreachable — 4.5MB of it, one file being the largest asset left in the
 * build. Only the canonical path needs to exist in the bucket.
 */
const MEDIA_TREES = [
  'wp-content',
  WEBP_PATH.replace(/^\/|\/$/g, ''),
  'wp-assets/wp-content/uploads',
];

/**
 * Drop the media from the deployment once a media host is serving it.
 *
 * Astro copies all of `public/` into the output and offers no way to filter it,
 * so this deletes afterwards rather than skipping the copy. The build pays the
 * copy either way; what changes is the 2.2GB that would otherwise be uploaded
 * to a static host on every deploy.
 *
 * Guarded on `MEDIA_ORIGIN` because without one the markup still points at
 * these paths, and deleting them would take every image on the site with it.
 */
async function dropMediaTrees(out, logger) {
  if (!MEDIA_ORIGIN) return;
  let freed = 0, count = 0;
  for (const tree of MEDIA_TREES) {
    const dir = path.join(out, tree);
    for (const f of await walk(dir)) {
      freed += (await fs.stat(f)).size;
      count++;
    }
    await fs.rm(dir, { recursive: true, force: true });
  }
  if (count) {
    logger.info(
      `dropped ${count} media files, ${(freed / 1048576).toFixed(0)}MB — served from ${MEDIA_ORIGIN}`
    );
  }
}

/** @returns {import('astro').AstroIntegration} */
export function hostFiles() {
  return {
    name: 'spenza:host-files',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        // Not `dir.pathname`: this project's own path contains a space, which
        // a URL keeps percent-encoded and `fs` then cannot find.
        const out = fileURLToPath(dir);

        const { body, count, skipped } = buildRedirects();
        await fs.writeFile(path.join(out, '_redirects'), body, 'utf8');
        logger.info(
          `_redirects: ${count} rules` + (skipped ? ` (${skipped} self-referential, skipped)` : '')
        );

        await fs.writeFile(
          path.join(out, '_headers'),
          NOINDEX ? HEADERS + NOINDEX_HEADERS : HEADERS,
          'utf8'
        );

        if (NOINDEX) {
          logger.warn('NOINDEX is set — this build tells search engines to stay away');
        } else if (!IS_DEFAULT_SITE) {
          logger.warn(
            'SITE_URL is overridden but NOINDEX is not set. If this is a preview ' +
            'deploy it will be indexable — set NOINDEX=1.'
          );
        }

        await extractInlineImages(out, logger);
        await hoistCssImports(out, logger);
        await pruneUnreferencedCss(out, logger);
        // After the prune, so it does not rewrite 932 stylesheets that are
        // about to be deleted, and before the media rewrite, which reads the
        // finished CSS.
        await fixFontLoading(out, logger);
        await rewriteAssetMedia(out, logger);
        await versionScripts(out, logger);
        // Last: everything above reads the output, and this removes part of it.
        await dropMediaTrees(out, logger);
      },
    },
  };
}
